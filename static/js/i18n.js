const ATTRS = ['placeholder', 'title', 'aria-label', 'alt'];
const NO_TEXT = new Set(['SCRIPT', 'STYLE', 'TEXTAREA', 'PRE', 'CODE', 'KBD']);
const HAS_LATIN = /[A-Za-z]/;

function lookup(key) {
  const hit = BN.get(key);
  if (hit !== undefined) return hit;
  for (const [re, rep] of PATTERNS) {
    if (re.test(key)) return key.replace(re, rep);
  }
  return undefined;
}

/** Translate one piece of interface text; unknown text is returned unchanged. */
export function tr(text) {
  const key = text.trim();
  if (!key || !HAS_LATIN.test(key)) return text;
  let out = lookup(key);
  // Messages built from several known sentences ("Here is the updated design. Some variants failed; …")
  // and meta lines joined with " · " ("DEMO placeholder - not AI (add an OpenAI key) · 3:2 · 2K").
  if (out === undefined) out = byParts(key, /(?<=[.!?])\s+/, ' ');
  if (out === undefined) out = byParts(key, ' · ', ' · ');
  if (out === undefined) return text;
  return text.slice(0, text.length - text.trimStart().length) + out + text.slice(text.trimEnd().length);
}

/** `key` split at `sep` with every known part translated; undefined when no part is known. */
function byParts(key, sep, glue) {
  const parts = key.split(sep);
  if (parts.length < 2) return undefined;
  const done = parts.map((p) => lookup(p));
  if (done.every((p) => p === undefined)) return undefined;
  return parts.map((p, i) => (done[i] === undefined ? p : done[i])).join(glue);
}

function skipped(el) {
  return Boolean(el && el.closest('[data-no-translate], textarea, pre, code, kbd, script, style'));
}

function translateAttrs(el) {
  for (const name of ATTRS) {
    const value = el.getAttribute(name);
    if (value) {
      // Multi-line tooltips (the header status) are translated line by line.
      const next = value.split('\n').map(tr).join('\n');
      if (next !== value) el.setAttribute(name, next);
    }
  }
}

function translateTree(node) {
  if (node.nodeType === Node.TEXT_NODE) {
    if (skipped(node.parentElement)) return;
    const next = tr(node.nodeValue);
    if (next !== node.nodeValue) node.nodeValue = next;
    return;
  }
  if (node.nodeType !== Node.ELEMENT_NODE) return;
  translateAttrs(node);
  if (NO_TEXT.has(node.tagName) || node.hasAttribute('data-no-translate')) return;
  for (const child of Array.from(node.childNodes)) translateTree(child);
}

document.documentElement.lang = 'bn';
document.title = tr(document.title);
translateTree(document.body);
new MutationObserver((mutations) => {
  for (const m of mutations) {
    if (m.type === 'childList') m.addedNodes.forEach(translateTree);
    else if (m.type === 'characterData') translateTree(m.target);
    // As in translateTree, an element's own attributes are translated even on a textarea (its
    // placeholder); only elements inside excluded content are left alone.
    else if (m.type === 'attributes' && !skipped(m.target.parentElement)) translateAttrs(m.target);
  }
}).observe(document.documentElement, {
  childList: true,
  subtree: true,
  characterData: true,
  attributes: true,
  attributeFilter: ATTRS,
});
