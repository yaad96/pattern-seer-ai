#!/usr/bin/env bash
# Start Jersey HD Studio at http://localhost:8000 (set HOST=0.0.0.0 to share it on your network).
set -euo pipefail
cd "$(dirname "$0")"

if [ ! -x .venv/bin/python ]; then
  PYTHON="${PYTHON:-python3}"
  "$PYTHON" -c 'import sys; sys.exit(0 if sys.version_info >= (3, 11) else 1)' \
    || { echo "Python 3.11 or newer is required (found: $("$PYTHON" --version 2>&1))." >&2; exit 1; }
  echo "Creating virtual environment and installing dependencies..."
  "$PYTHON" -m venv .venv
  .venv/bin/pip install --quiet --upgrade pip
  .venv/bin/pip install --quiet -r requirements.txt
fi

for f in .openai_api_key .anthropic_api_key; do
  [ -e "$f" ] || { : > "$f"; chmod 600 "$f"; }
done

if ! grep -q '[^[:space:]]' .openai_api_key; then
  echo ""
  echo "  WARNING: .openai_api_key is empty -> DEMO MODE (placeholder images, no AI)."
  echo "  Images are generated by OpenAI only; Claude cannot create images."
  echo "  Paste your OpenAI key into .openai_api_key, then run ./run.sh again."
  echo ""
fi

exec .venv/bin/python -m uvicorn app.main:app --host "${HOST:-127.0.0.1}" --port "${PORT:-8000}"
